"""Enemy ranks: 64 new enemies (8 per act) and every boss's extra skill + special attacks.

Ranks (see ranks.csv): Minion < Soldier < Elite < Champion < Boss. A rank fixes how many skills an enemy has besides its
basic attack (Minion 0, Soldier 1, Elite 2 = active + passive, Champion 3 = two actives + passive, Boss 4+ = active,
extra active, passive and special attacks), and its HP multiplier and XP in ranks.csv. Existing enemies keep their skills
and get the rank their skill count gives (gen_campaign.py derives it).

gen_campaign.py adds NEW_ENEMIES to their act's enemies and to the chapters listed in NEW_FOES, and BOSS_KITS to the bosses.
Specials charge once when the boss's HP first drops to the threshold and fire on its next turn (cooldowns and silence do
not stop them; a stun only delays them).
"""


def N(key, name, rank, role, tint, active=None, extra=None, passive=None, scale=1.0):
    """New enemy. rank: Minion|Soldier|Elite|Champion. active/extra = S(...), passive = PS(...)."""
    return dict(key=key, name=name, rank=rank, role=role, tint=tint, active=active, extra=extra, passive=passive, art=None, scale=scale)


def S(name, desc, targeting, cooldown, effects, count=1):
    return dict(name=name, desc=desc, targeting=targeting, cooldown=cooldown, effects=effects, count=count)


def PS(name, desc, trigger, effects, targeting='Self', threshold=0, chance=0, cooldown=0, once=False, count=1):
    return dict(name=name, desc=desc, trigger=trigger, effects=effects, targeting=targeting, threshold=threshold,
                chance=chance, cooldown=cooldown, once=once, count=count)


def SP(name, desc, targeting, threshold, effects, count=1):
    """Boss special attack (fires once when HP first drops to `threshold`)."""
    return dict(name=name, desc=desc, targeting=targeting, threshold=threshold, effects=effects, count=count)


def K(extra, specials, passive=None):
    """Boss kit: one extra active, its special attacks (falling thresholds) and a passive for bosses that had none."""
    return dict(extra=extra, specials=specials, passive=passive)


