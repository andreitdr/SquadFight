"""Design table for the 90 heroes added in "The Hundred" (the 10 original heroes stay hand-written in the CSVs).

One entry per hero: key, display name, class, origin act, lore, recruitment line, active skill and passive.
Rarity and stat lean are NOT set here: gen_roster.py rolls them (seeded) so rarity is random per hero, as the owner asked.

A(name, description, targeting, cooldown, effects, count=1, initial=1)
P(name, description, trigger, effects, targeting='Self', count=1, threshold=0, chance=0, cooldown=0, once=False)
Effects use the skills.csv mini-syntax (CONTENT_SCHEMA.md).
"""


def A(name, desc, targeting, cooldown, effects, count=1, initial=1):
    return dict(name=name, desc=desc, targeting=targeting, cooldown=cooldown, effects=effects, count=count, initial=initial)


def P(name, desc, trigger, effects, targeting='Self', count=1, threshold=0, chance=0, cooldown=0, once=False):
    return dict(name=name, desc=desc, trigger=trigger, effects=effects, targeting=targeting, count=count,
                threshold=threshold, chance=chance, cooldown=cooldown, once=once)


def H(key, name, cls, act, lore, line, active, passive):
    return dict(key=key, name=name, cls=cls, act=act, lore=lore, line=line, active=active, passive=passive)


